import os
import sys
import argparse
import xml.etree.ElementTree as ET
import pandas as pd
from typing import Dict, Any, List


def parse_flowmon_xml(xml_path: str) -> List[Dict[str, Any]]:
    if not os.path.exists(xml_path):
        raise FileNotFoundError(f"FlowMonitor XML file not found: {xml_path}")

    tree = ET.parse(xml_path)
    root = tree.getroot()

    # Build flow classification map (flowId -> 5-tuple)
    flow_map = {}
    classifier = root.find("Ipv4FlowClassifier")
    if classifier is not None:
        for flow_elem in classifier.findall("Flow"):
            flow_id = int(flow_elem.get("flowId"))
            flow_map[flow_id] = {
                "sourceAddress": flow_elem.get("sourceAddress"),
                "destinationAddress": flow_elem.get("destinationAddress"),
                "sourcePort": int(flow_elem.get("sourcePort")),
                "destinationPort": int(flow_elem.get("destinationPort")),
                "protocol": int(flow_elem.get("protocol"))
            }

    flow_stats_elem = root.find("FlowStats")
    if flow_stats_elem is None:
        return []

    records = []
    for flow in flow_stats_elem.findall("Flow"):
        flow_id = int(flow.get("flowId"))
        tx_packets = int(flow.get("txPackets", 0))
        rx_packets = int(flow.get("rxPackets", 0))
        tx_bytes = int(flow.get("txBytes", 0))
        rx_bytes = int(flow.get("rxBytes", 0))
        lost_packets = int(flow.get("lostPackets", 0))
        
        # NS-3 FlowMonitor exports time in nanoseconds
        time_first_tx_ns = float(flow.get("timeFirstTxPacket", "0").replace("ns", "").replace("+", ""))
        time_last_rx_ns = float(flow.get("timeLastRxPacket", "0").replace("ns", "").replace("+", ""))
        delay_sum_ns = float(flow.get("delaySum", "0").replace("ns", "").replace("+", ""))
        jitter_sum_ns = float(flow.get("jitterSum", "0").replace("ns", "").replace("+", ""))

        duration_s = (time_last_rx_ns - time_first_tx_ns) / 1e9 if time_last_rx_ns > time_first_tx_ns else 0.0
        throughput_kbps = (rx_bytes * 8.0) / (duration_s * 1000.0) if duration_s > 0 else 0.0
        pdr_pct = (rx_packets / tx_packets * 100.0) if tx_packets > 0 else 0.0
        mean_delay_ms = (delay_sum_ns / rx_packets) / 1e6 if rx_packets > 0 else 0.0
        mean_jitter_ms = (jitter_sum_ns / (rx_packets - 1)) / 1e6 if rx_packets > 1 else 0.0

        meta = flow_map.get(flow_id, {})
        dest_port = meta.get("destinationPort", 0)

        # Label clinical flow zone
        if dest_port == 5001:
            zone = "ICU Telemetry (UDP)"
        elif dest_port == 5002:
            zone = "PACS Imaging (TCP)"
        elif dest_port == 5003:
            zone = "Clinic Triage (UDP)"
        elif dest_port == 5004:
            zone = "Clinical Voice (VoIP)"
        elif dest_port == 5005:
            zone = "Guest Network (BE)"
        else:
            zone = "Other / Control"

        records.append({
            "flow_id": flow_id,
            "zone": zone,
            "src": meta.get("sourceAddress", "N/A"),
            "dst": meta.get("destinationAddress", "N/A"),
            "src_port": meta.get("sourcePort", 0),
            "dst_port": dest_port,
            "proto": "TCP" if meta.get("protocol") == 6 else ("UDP" if meta.get("protocol") == 17 else str(meta.get("protocol"))),
            "tx_packets": tx_packets,
            "rx_packets": rx_packets,
            "lost_packets": lost_packets,
            "pdr_pct": round(pdr_pct, 2),
            "throughput_kbps": round(throughput_kbps, 2),
            "mean_delay_ms": round(mean_delay_ms, 2),
            "jitter_ms": round(mean_jitter_ms, 2),
            "duration_s": round(duration_s, 2)
        })

    return records


def main():
    parser = argparse.ArgumentParser(description="Parse NS-3 FlowMonitor XML files and generate summary metrics.")
    parser.add_argument("xml_file", help="Path to input FlowMonitor XML file (e.g. flowmon.xml)")
    parser.add_argument("--output-csv", "-o", help="Optional path to export tabular metrics CSV")
    args = parser.parse_args()

    try:
        records = parse_flowmon_xml(args.xml_file)
        if not records:
            print("[WARN] No active flows found in FlowMonitor XML.")
            sys.exit(0)

        df = pd.DataFrame(records)
        print("=" * 88)
        print("  NS-3 FLOWMONITOR PERFORMANCE SUMMARY")
        print("=" * 88)
        print(df[["flow_id", "zone", "proto", "tx_packets", "rx_packets", "pdr_pct", "throughput_kbps", "mean_delay_ms"]].to_string(index=False))
        print("=" * 88)

        if args.output_csv:
            df.to_csv(args.output_csv, index=False)
            print(f"[SUCCESS] Exported {len(df)} flow records to {args.output_csv}")

    except Exception as e:
        print(f"[ERROR] Failed to parse FlowMonitor file: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()

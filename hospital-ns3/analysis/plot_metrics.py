import os
import sys
import argparse
import pandas as pd
import matplotlib.pyplot as plt


def plot_flow_metrics(csv_path: str, output_dir: str):
    os.makedirs(output_dir, exist_ok=True)
    df = pd.read_csv(csv_path)

    # 1. Throughput by Clinical Zone
    if "zone" in df.columns and "throughput_kbps" in df.columns:
        plt.figure(figsize=(10, 6))
        bars = plt.bar(df["zone"], df["throughput_kbps"], color=["#1f77b4", "#ff7f0e", "#2ca02c", "#d62728", "#9467bd"][:len(df)])
        plt.title("NS-3 Hospital Simulation: Aggregated Throughput by Clinical Zone", fontsize=13, fontweight="bold")
        plt.xlabel("Clinical Traffic Zone / Protocol", fontsize=11)
        plt.ylabel("Throughput (kbps)", fontsize=11)
        plt.xticks(rotation=20, ha="right")
        plt.grid(axis="y", linestyle="--", alpha=0.5)

        for bar in bars:
            height = bar.get_height()
            plt.annotate(f"{height:.1f} kbps",
                         xy=(bar.get_x() + bar.get_width() / 2, height),
                         xytext=(0, 4), textcoords="offset points",
                         ha="center", va="bottom", fontsize=9, fontweight="bold")

        plt.tight_layout()
        out_png = os.path.join(output_dir, "ns3_zone_throughput.png")
        out_pdf = os.path.join(output_dir, "ns3_zone_throughput.pdf")
        plt.savefig(out_png, dpi=300)
        plt.savefig(out_pdf)
        plt.close()
        print(f"[OK] Generated: {out_png}")

    # 2. End-to-End Delay vs Clinical SLA
    if "zone" in df.columns and "mean_delay_ms" in df.columns:
        plt.figure(figsize=(10, 6))
        bars = plt.bar(df["zone"], df["mean_delay_ms"], color="#2b5c8f")
        plt.axhline(y=3000.0, color="red", linestyle="--", linewidth=2, label="Clinical Vitals SLA Max (3000 ms)")
        plt.title("NS-3 Hospital Simulation: Mean End-to-End Delay vs. SLA", fontsize=13, fontweight="bold")
        plt.xlabel("Clinical Traffic Zone", fontsize=11)
        plt.ylabel("Mean Latency (ms)", fontsize=11)
        plt.xticks(rotation=20, ha="right")
        plt.legend(loc="upper right")
        plt.grid(axis="y", linestyle="--", alpha=0.5)

        for bar in bars:
            height = bar.get_height()
            plt.annotate(f"{height:.2f} ms",
                         xy=(bar.get_x() + bar.get_width() / 2, height),
                         xytext=(0, 4), textcoords="offset points",
                         ha="center", va="bottom", fontsize=9, fontweight="bold")

        plt.tight_layout()
        out_png = os.path.join(output_dir, "ns3_latency_sla.png")
        out_pdf = os.path.join(output_dir, "ns3_latency_sla.pdf")
        plt.savefig(out_png, dpi=300)
        plt.savefig(out_pdf)
        plt.close()
        print(f"[OK] Generated: {out_png}")


def main():
    parser = argparse.ArgumentParser(description="Plot publication charts from NS-3 metrics CSV.")
    parser.add_argument("csv_file", help="Path to input metrics CSV generated by parse_flowmon.py")
    parser.add_argument("--outdir", "-o", default="results", help="Target output directory for charts")
    args = parser.parse_args()

    plot_flow_metrics(args.csv_file, args.outdir)


if __name__ == "__main__":
    main()
